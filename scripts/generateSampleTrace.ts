import * as fs from 'fs';
import * as path from 'path';
import { ResearchOrchestrator } from '../src/lib/agents/orchestrator';
import { TraceFormatter } from '../src/lib/agents/traceFormatter';

async function main() {
  console.log('Generating sample execution trace...');
  const orchestrator = new ResearchOrchestrator(
    'Commercial Viability of Solid-State Batteries by 2030',
    'standard',
    'executive',
    'all',
    true, // redTeam enabled to trigger critical scrutiny
    undefined,
    [],
    { mockMode: true }
  );

  const state = await orchestrator.run();
  if (!state.trace) {
    throw new Error('Trace was not generated by orchestrator.');
  }

  const docsDir = path.join(__dirname, '..', 'docs');
  if (!fs.existsSync(docsDir)) {
    fs.mkdirSync(docsDir, { recursive: true });
  }

  const jsonPath = path.join(docsDir, 'sample_trace.json');
  fs.writeFileSync(jsonPath, JSON.stringify(state.trace, null, 2), 'utf-8');
  console.log(`Saved JSON trace to: ${jsonPath}`);

  const mdContent = TraceFormatter.toMarkdown(state.trace);
  const mdPath = path.join(docsDir, 'sample_trace.md');
  fs.writeFileSync(mdPath, mdContent, 'utf-8');
  console.log(`Saved Markdown trace to: ${mdPath}`);
}

main().catch(err => {
  console.error('Failed to generate sample trace:', err);
  process.exit(1);
});
